#include <iostream>

using namespace std;

int main() {
    int k;
    cin >> k;
    int sum = 0;
    for(int i = 0; i < k; i++) {
        int x;
        cin >> x;
        sum += x;
    }
    cout << sum << endl;
    return 0;
}
